// Build csbot's map geometry from the CS2 map files on this PC (read-only) into
// packages/engine/src/maps/geo/<map>.ts, plus a preview per map in tools/map-build/out/.
//
//   node tools/map-build/src/build.ts            all maps in the pool
//   node tools/map-build/src/build.ts de_dust2   one map
//
// CSBOT_CS2_DIR overrides the game folder (…/game/csgo).

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import type { MapGeo } from '@csbot/engine/geometry';
import { POOL } from './config.ts';
import { buildGeo } from './geo.ts';
import { defaultCsgoDir, loadMapSource } from './source.ts';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '../../..');
const outGeo = path.join(repo, 'packages/engine/src/maps/geo');
const outPreview = path.join(here, '../out');

export function geoModule(geo: MapGeo): string {
  const name = 'GEO_' + geo.id.replace(/^de_/, '').toUpperCase();
  const lines = [
    `// Generated by tools/map-build from the CS2 map files (nav mesh and callout volumes). Do not edit:`,
    `// change tools/map-build/src/config.ts and run \`node tools/map-build/src/build.ts ${geo.id}\`.`,
    `import type { MapGeo } from '../../geometry.ts';`,
    ``,
    `export const ${name}: MapGeo = {`,
    `  id: ${JSON.stringify(geo.id)},`,
    `  name: ${JSON.stringify(geo.name)},`,
    `  world: ${JSON.stringify(geo.world)},`,
    `  spawn: ${JSON.stringify(geo.spawn)},`,
    `  zones: [`,
    ...geo.zones.map(z => `    ${JSON.stringify(z)},`),
    `  ],`,
    `  arrive: ${JSON.stringify(geo.arrive)},`,
    `  nodes: ${JSON.stringify(geo.nodes)},`,
    `  portals: ${JSON.stringify(geo.portals)},`,
    `  edges: [`,
    ...geo.edges.map(e => `    ${JSON.stringify(e)},`),
    `  ],`,
    `  floor: ${JSON.stringify(geo.floor)},`,
    `  grid: ${JSON.stringify(geo.grid)},`,
    `};`,
    ``,
  ];
  return lines.join('\n');
}

/** A standalone SVG to eyeball the result: floor, zones, labels, hubs and graph edges. */
export function previewSvg(geo: MapGeo): string {
  const hue = (i: number) => (i * 47) % 360;
  let svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1000 1000" width="1000" height="1000"><rect width="1000" height="1000" fill="#14171c"/>`;
  svg += `<path d="${geo.floor}" fill="#2a303b" fill-rule="evenodd" stroke="#4a5263" stroke-width="2"/>`;
  geo.zones.forEach((z, i) => { svg += `<path d="${z.path}" fill="hsla(${hue(i)},70%,55%,${z.site ? 0.3 : 0.12})" fill-rule="evenodd" stroke="hsl(${hue(i)},70%,60%)" stroke-width="1"/>`; });
  for (const e of geo.edges) {
    const a = geo.nodes[e[0]!]!, b = geo.nodes[e[1]!]!;
    const pts = [a, ...Array.from({ length: (e.length - 3) / 2 }, (_, k) => [e[3 + 2 * k]!, e[4 + 2 * k]!]), b];
    svg += `<polyline points="${pts.map(p => p.join(',')).join(' ')}" fill="none" stroke="rgba(255,255,255,.25)" stroke-width="1"/>`;
  }
  geo.zones.forEach(z => {
    const [t, ct] = geo.arrive[z.id] ?? [-1, -1];
    svg += `<text x="${z.at[0]}" y="${z.at[1]}" fill="#fff" font-size="12" font-family="Segoe UI" text-anchor="middle" stroke="#000" stroke-width="3" paint-order="stroke">${z.name}</text>`;
    svg += `<text x="${z.at[0]}" y="${z.at[1] + 12}" fill="#f6c177" font-size="9" font-family="Segoe UI" text-anchor="middle" stroke="#000" stroke-width="2" paint-order="stroke">T ${t}s · CT ${ct}s</text>`;
  });
  svg += `<circle cx="${geo.spawn.T[0]}" cy="${geo.spawn.T[1]}" r="6" fill="#c98500"/><circle cx="${geo.spawn.CT[0]}" cy="${geo.spawn.CT[1]}" r="6" fill="#3987e5"/>`;
  return svg + '</svg>';
}

function main(): void {
  const csgo = defaultCsgoDir();
  if (!fs.existsSync(csgo)) throw new Error(`CS2 not found at ${csgo} (set CSBOT_CS2_DIR)`);
  const want = process.argv.slice(2);
  const maps = want.length ? POOL.filter(m => want.includes(m.id)) : POOL;
  if (!maps.length) throw new Error(`unknown map: ${want.join(', ')}`);
  fs.mkdirSync(outGeo, { recursive: true });
  fs.mkdirSync(outPreview, { recursive: true });
  for (const cfg of maps) {
    const t0 = Date.now();
    const { geo, report } = buildGeo(loadMapSource(cfg.id, csgo), cfg);
    const file = path.join(outGeo, `${cfg.id}.ts`);
    fs.writeFileSync(file, geoModule(geo));
    fs.writeFileSync(path.join(outPreview, `${cfg.id}.svg`), previewSvg(geo));
    const kb = (fs.statSync(file).size / 1024).toFixed(0);
    console.log(`${cfg.id.padEnd(11)} ${report.areas} areas → ${report.zones} zones, ${report.edges} edges, ${kb} KB, ${Date.now() - t0} ms`);
    for (const w of report.warnings) console.log(`  ! ${w}`);
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
